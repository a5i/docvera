const { spawnSync } = require('node:child_process');
const { copyFileSync } = require('node:fs');
const { resolve, join } = require('node:path');
const root = resolve(__dirname, '../..');
const release = process.argv.includes('--release');
const target = join(root, 'target');
const result = spawnSync('cargo', ['build', '--locked', '-p', 'md-node', '--target-dir', target, ...(release ? ['--release'] : [])], { cwd: root, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const library = { win32: 'md_node.dll', darwin: 'libmd_node.dylib', linux: 'libmd_node.so' }[process.platform];
if (!library) throw new Error(`Unsupported platform: ${process.platform}`);
copyFileSync(join(target, release ? 'release' : 'debug', library), join(__dirname, 'md_engine.node'));
copyFileSync(join(root, 'LICENSE'), join(__dirname, 'LICENSE'));
